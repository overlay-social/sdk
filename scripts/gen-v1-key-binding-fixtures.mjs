// Regenerates test/fixtures/schema/v1-key-binding.json: the exact key-binding
// output script the peck.to v1 web client produces in its identity bootstrap
// (`bootstrapIdentity`, used by /welcome).
//
// The fixture is not hand-written. This script runs v1's own `bootstrapIdentity`
// from the v1 browser bundle (public/js/app.js) in a node `vm`, with a stub
// browser and a fixed BRC-100 ProtoWallet, and captures the first output of the
// `createAction` call it makes (the binding; the profile and handle outputs that
// follow it are not kept).
//
// The v1 sources are not in this repository. Point the script at a checkout:
//
//   node scripts/gen-v1-key-binding-fixtures.mjs --app <v1>/public/js/app.js [--v1-rev <sha>]
//
// All signing here is deterministic (fixed wallet keys, RFC 6979 ECDSA, fixed
// serials), so the output is reproducible. Run it under node, never bun.
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { TextEncoder } from 'node:util'
import vm from 'node:vm'
import { PrivateKey, ProtoWallet } from '@bsv/sdk'

if (process.versions.bun) throw new Error('run this under node, not bun')

const arg = (name) => {
  const i = process.argv.indexOf(name)
  return i > 0 ? process.argv[i + 1] : undefined
}
const appPath = arg('--app')
if (!appPath) {
  console.error('usage: gen-v1-key-binding-fixtures.mjs --app <app.js> [--v1-rev <sha>]')
  process.exit(2)
}

const appSource = readFileSync(resolve(appPath), 'utf8').split('\n')

/** The source of one method of the v1 object literals (8-space indent, closed by `        },`). */
function method(signature) {
  const start = appSource.findIndex((l) => l.startsWith(`        ${signature}`))
  if (start < 0) throw new Error(`v1 method not found: ${signature}`)
  let end = start + 1
  while (appSource[end] !== '        },') end++
  return appSource.slice(start, end + 1).join('\n').replace(/,$/, '')
}

const clone = (v) => JSON.parse(JSON.stringify(v))

/** Runs v1's bootstrapIdentity with `walletKey` and serial bytes `serial`; returns the binding script. */
async function v1Binding(walletKey, serialHex) {
  const wallet = new ProtoWallet(new PrivateKey(walletKey))
  const serialBytes = serialHex.match(/../g).map((h) => parseInt(h, 16))
  const actions = []
  const win = {
    location: { href: 'https://peck.to/welcome' },
    walletRequest: async (m, p) => {
      if (m === 'getPublicKey') return wallet.getPublicKey(clone(p))
      if (m === 'createSignature') return wallet.createSignature(clone(p))
      if (m === 'createAction') {
        actions.push(clone(p))
        return { txid: '00'.repeat(32), tx: '0100beef' }
      }
      throw new Error(`unexpected wallet call ${m}`)
    },
  }
  const context = vm.createContext({
    window: win,
    TextEncoder,
    crypto: {
      getRandomValues(a) {
        for (let i = 0; i < a.length; i++) a[i] = serialBytes[i]
        return a
      },
    },
    // The avatar generator answers with none; the overlay /submit answers ok.
    fetch: async () => ({ ok: true, status: 200, json: async () => ({}) }),
    console: { log() {}, warn() {}, error() {} },
  })
  const bootstrapIdentity = vm.runInContext(`({ ${method('async bootstrapIdentity(')} })`, context).bootstrapIdentity
  const result = await bootstrapIdentity('fixture_user', 'Fixture User')
  const out = actions[0]?.outputs?.[0]
  if (!out || out.outputDescription !== 'key-binding') throw new Error('v1 did not write a key-binding output first')
  return {
    identityKey: (await wallet.getPublicKey({ identityKey: true })).publicKey,
    subjectKey: result.subject,
    scriptHex: out.lockingScript,
  }
}

const cases = [
  { note: 'the parity wallet (key 20261006), serial 0f1e2d3c4b5a6978', walletKey: 20261006, serial: '0f1e2d3c4b5a6978' },
  { note: 'another wallet (key 424242), serial a1b2c3d4e5f60718', walletKey: 424242, serial: 'a1b2c3d4e5f60718' },
  { note: 'a third wallet (key 7), serial ffffffffffffffff', walletKey: 7, serial: 'ffffffffffffffff' },
]
const bindings = []
for (const c of cases) bindings.push({ ...c, ...(await v1Binding(c.walletKey, c.serial)) })

const out = {
  about:
    'Generated by scripts/gen-v1-key-binding-fixtures.mjs from the peck.to v1 client code (bootstrapIdentity, ' +
    'its key-binding output). Do not edit by hand.',
  v1Rev: arg('--v1-rev') ?? null,
  bindings,
}
const target = resolve(import.meta.dirname, '../test/fixtures/schema/v1-key-binding.json')
writeFileSync(target, JSON.stringify(out, null, 2) + '\n')
console.log(`wrote ${bindings.length} key bindings to ${target}`)
