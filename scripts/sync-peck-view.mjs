// Vendors the peck-view/v1 contract (the JSON Schema behind the overlay's /v2
// read model) into the SDK and regenerates the TypeScript types from it.
//
//   npm run sync:peck-view -- <path/to/peck-view.schema.json> [--examples <dir>]
//       Copy the schema to src/read/peck-view/, regenerate types.ts, and copy the
//       contract's examples (default: an `examples/` folder next to the schema)
//       to test/fixtures/peck-view/.
//   npm run check:peck-view
//       Regenerate types.ts from the vendored schema in memory and exit 1 when the
//       committed file differs (run in CI).
//
// The overlay owns the contract; this package only consumes it. Never edit the
// vendored schema or types.ts by hand: re-run the sync against the contract.
import { createHash } from 'node:crypto'
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { basename, dirname, join, resolve } from 'node:path'
import { compile } from 'json-schema-to-typescript'

const ROOT = resolve(import.meta.dirname, '..')
const CONTRACT = 'peck-view/v1'
const SCHEMA_OUT = join(ROOT, 'src/read/peck-view/peck-view.schema.json')
const TYPES_OUT = join(ROOT, 'src/read/peck-view/types.ts')
const FIXTURES_OUT = join(ROOT, 'test/fixtures/peck-view')

// Description text in the upstream schema can point into the producer's own
// source tree (file paths, build commands, deployment settings). Those mean
// nothing to SDK users, so they are dropped from `description` strings here.
// Only prose is touched: no keyword, type or constraint is ever rewritten.
const DESCRIPTION_REWRITES = [
  [/\s*\((?:\w+ in )?src\/[^()]*\)/g, ''],
  [/\s*Generated TypeScript types: [^.]*\.d\.ts(?: \([^)]*\))?\./g, ''],
  [/\s*\(overlay env [A-Z0-9_]+\)/g, ''],
  [/<UHRP_PUBLIC_BASE>/g, '<UHRP base>'],
  [/\s*\([\w-]+ conventions: ([^)]*)\)/g, ' ($1)'],
]
// Anything still matching after the rewrites stops the sync, so a new internal
// reference upstream is noticed instead of being published.
const FORBIDDEN_IN_DESCRIPTIONS = /src\/|\.d\.ts|npm run|conventions:|\b[A-Z][A-Z0-9]*_[A-Z0-9_]{2,}\b/

function cleanDescriptions(node, path = '$') {
  if (Array.isArray(node)) return node.map((v, i) => cleanDescriptions(v, `${path}[${i}]`))
  if (node === null || typeof node !== 'object') return node
  const out = {}
  for (const [k, v] of Object.entries(node)) {
    if (k === 'description' && typeof v === 'string') {
      let text = v
      for (const [re, to] of DESCRIPTION_REWRITES) text = text.replace(re, to)
      if (FORBIDDEN_IN_DESCRIPTIONS.test(text)) {
        throw new Error(`${path}.description still names producer internals after cleaning:\n  ${text}`)
      }
      out[k] = text
    } else {
      out[k] = cleanDescriptions(v, `${path}.${k}`)
    }
  }
  return out
}

function banner(sourceSha256) {
  return `/**
 * ${CONTRACT}: the hydrated read model served by the overlay under /v2.
 *
 * GENERATED by scripts/sync-peck-view.mjs from the vendored contract
 * (src/read/peck-view/peck-view.schema.json). Do not edit by hand: re-run
 * \`npm run sync:peck-view -- <path to the contract schema>\`.
 *
 * Contract source sha256: ${sourceSha256}
 */`
}

async function generateTypes(schema, sourceSha256) {
  return compile(schema, 'PeckView', {
    bannerComment: banner(sourceSha256),
    // Emit every $defs entry, including ones only reachable from each other.
    unreachableDefinitions: true,
    additionalProperties: false,
    // Refs keep their own names (Txid, AuthorView, …) instead of being inlined.
    declareExternallyReferenced: true,
    enableConstEnums: false,
    strictIndexSignatures: false,
    format: true,
    style: { singleQuote: true, semi: false, printWidth: 100 },
  })
}

function readVendored() {
  const text = readFileSync(SCHEMA_OUT, 'utf8')
  const schema = JSON.parse(text)
  const sha = /source sha256 ([0-9a-f]{64})/.exec(schema.$comment ?? '')?.[1]
  if (!sha) throw new Error(`${SCHEMA_OUT}: $comment does not name the source sha256`)
  return { schema, sha }
}

async function check() {
  const { schema, sha } = readVendored()
  const generated = await generateTypes(schema, sha)
  const current = existsSync(TYPES_OUT) ? readFileSync(TYPES_OUT, 'utf8') : ''
  if (current !== generated) {
    console.error(`${TYPES_OUT} is stale. Run: npm run sync:peck-view -- <path to the contract schema>`)
    process.exit(1)
  }
  console.log(`${CONTRACT} types are up to date (source sha256 ${sha.slice(0, 12)}…)`)
}

async function sync(schemaPath, examplesDir) {
  const raw = readFileSync(schemaPath)
  const sha = createHash('sha256').update(raw).digest('hex')
  const upstream = JSON.parse(raw.toString('utf8'))
  const cleaned = cleanDescriptions(upstream)
  // Record which contract revision this copy came from (JSON has no comments).
  const vendored = {
    $schema: cleaned.$schema,
    $id: cleaned.$id,
    $comment: `Vendored copy of the ${CONTRACT} contract (source sha256 ${sha}). Written by scripts/sync-peck-view.mjs; do not edit by hand.`,
    ...cleaned,
  }
  mkdirSync(dirname(SCHEMA_OUT), { recursive: true })
  writeFileSync(SCHEMA_OUT, `${JSON.stringify(vendored, null, 2)}\n`)
  writeFileSync(TYPES_OUT, await generateTypes(vendored, sha))
  console.log(`wrote ${SCHEMA_OUT}\nwrote ${TYPES_OUT}`)

  if (examplesDir && existsSync(examplesDir)) {
    rmSync(FIXTURES_OUT, { recursive: true, force: true })
    mkdirSync(FIXTURES_OUT, { recursive: true })
    const files = readdirSync(examplesDir).filter((f) => f.endsWith('.json')).sort()
    for (const f of files) copyFileSync(join(examplesDir, f), join(FIXTURES_OUT, basename(f)))
    console.log(`copied ${files.length} examples to ${FIXTURES_OUT}`)
  } else {
    console.log('no examples folder found; test fixtures left unchanged')
  }
}

const args = process.argv.slice(2)
if (args.includes('--check')) {
  await check()
} else {
  const schemaPath = args.find((a) => !a.startsWith('--') && args[args.indexOf(a) - 1] !== '--examples')
  if (!schemaPath) {
    console.error('usage: npm run sync:peck-view -- <path/to/peck-view.schema.json> [--examples <dir>]')
    process.exit(2)
  }
  const i = args.indexOf('--examples')
  const examplesDir = i >= 0 ? args[i + 1] : join(dirname(resolve(schemaPath)), 'examples')
  await sync(resolve(schemaPath), examplesDir && resolve(examplesDir))
}
